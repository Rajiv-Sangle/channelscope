"""ClinVar, for M01's check G4: the summary plan, and parsing E-utilities summaries into comparable variants. Pure.

Only what G4 compares is parsed: the GRCh38 location, the canonical SPDI, and the HGVS c. and p. descriptions in the
record's title on NM_000540.3. Anything that cannot be parsed is kept with the reason, never dropped silently.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field

import yaml

EUTILS = "https://eutils.ncbi.nlm.nih.gov/entrez/eutils/esummary.fcgi"


def summary_plan(esearch_json: bytes, batch: int, stored_prefix: str) -> str:
    """A fetch plan (YAML text) that summarises every id an E-utilities search returned, in batches."""
    result = json.loads(esearch_json)["esearchresult"]
    ids = result["idlist"]
    if int(result["count"]) != len(ids):
        raise ValueError(f"the search counted {result['count']} records but returned {len(ids)} ids")
    calls = []
    for n, start in enumerate(range(0, len(ids), batch), start=1):
        chunk = ids[start:start + batch]
        calls.append({"name": f"clinvar_summaries_{n}", "source": "source:clinvar",
                      "url": f"{EUTILS}?db=clinvar&id={','.join(chunk)}&retmode=json&tool=channelscope",
                      "stored_at": f"{stored_prefix}_{n}.json", "release_absent": "unknown", "pause_s": 0.4})
    header = (f"# Generated by channelscope.clinvar.summary_plan from the esearch snapshot: {len(ids)} ids in "
              f"{len(calls)} batch(es) of up to {batch}.\n")
    return header + yaml.safe_dump({"calls": calls}, sort_keys=False, width=100000)


TITLE = re.compile(r"^(?P<tx>N[MR]_\d+\.\d+)\((?P<gene>[^)]+)\):(?P<c>c\.\S+)(?: \((?P<p>p\.[^)]+)\))?$")
C_SUB = re.compile(r"^c\.(?P<pos>[-*]?\d+(?:[+-]\d+)?)(?P<ref>[ACGT])>(?P<alt>[ACGT])$")
C_POS = re.compile(r"[-*]?\d+(?:[+-]\d+)?")
P_DESC = re.compile(r"^p\.(?P<ref>[A-Z][a-z]{2})(?P<pos>\d+)(?P<rest>.*)$")


@dataclass
class ClinVarVariant:
    uid: str
    accession: str
    title: str
    transcript: str | None = None
    c: str | None = None
    p: str | None = None
    grch38_chr: str | None = None
    grch38_start: int | None = None
    grch38_stop: int | None = None
    spdi: str | None = None
    problems: list[str] = field(default_factory=list)

    @property
    def is_substitution(self) -> bool:
        return bool(self.c and C_SUB.match(self.c))

    @property
    def c_positions(self) -> list[str]:
        """The c. position(s) named in the description: one for a substitution, two for a range."""
        if not self.c:
            return []
        body = self.c[2:]
        if "_" in body:
            first, second = body.split("_", 1)
            return [C_POS.match(first).group(0), C_POS.match(second).group(0)]  # type: ignore[union-attr]
        m = C_POS.match(body)
        return [m.group(0)] if m else []

    @property
    def is_intronic(self) -> bool:
        return any(re.search(r"\d[+-]\d", p) for p in self.c_positions)


def parse_summaries(esummary_json: bytes) -> list[ClinVarVariant]:
    result = json.loads(esummary_json)["result"]
    out = []
    for uid in result["uids"]:
        d = result[uid]
        v = ClinVarVariant(uid=uid, accession=d.get("accession", ""), title=d.get("title", ""))
        m = TITLE.match(v.title)
        if m:
            v.transcript, v.c, v.p = m.group("tx"), m.group("c"), m.group("p")
        else:
            v.problems.append("title is not a single HGVS c. description on a transcript")
        sets = d.get("variation_set", [])
        if len(sets) != 1:
            v.problems.append(f"{len(sets)} variation sets")
        else:
            v.spdi = sets[0].get("canonical_spdi") or None
            locs = [loc for loc in sets[0].get("variation_loc", []) if loc.get("assembly_name") == "GRCh38"]
            if len(locs) == 1:
                v.grch38_chr = locs[0].get("chr")
                v.grch38_start, v.grch38_stop = int(locs[0]["start"]), int(locs[0]["stop"])
            else:
                v.problems.append(f"{len(locs)} GRCh38 locations")
        out.append(v)
    return out


