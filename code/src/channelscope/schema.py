"""The JSON Schema, generated from the models and checked byte-equal to what is committed (ADR-001 §7).

`write` regenerates the files; `check` regenerates them in memory and reports every file whose committed bytes
differ, is missing, or is not generated. Pydantic emits JSON Schema draft 2020-12.
"""

from __future__ import annotations

import json
from pathlib import Path

from pydantic import TypeAdapter

from .models import RECORD_TYPES, SCHEMA_VERSION, AnyRecord

DIALECT = "https://json-schema.org/draft/2020-12/schema"
MAJOR_MINOR = ".".join(SCHEMA_VERSION.split(".")[:2])


def _dump(schema: dict) -> bytes:
    return (json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")


def generate() -> dict[str, bytes]:
    """File name -> bytes: one schema per record type, and `record.schema.json` for any record (by `type`)."""
    out: dict[str, bytes] = {}
    for model in RECORD_TYPES:
        name = model.model_fields["type"].annotation.__args__[0]
        schema = {"$schema": DIALECT, **model.model_json_schema()}
        out[f"{name}.schema.json"] = _dump(schema)
    union = {"$schema": DIALECT, "title": "Record",
             "description": f"Any record of the ChannelScope evidence graph, schema {SCHEMA_VERSION}, "
                            f"discriminated by `type`.",
             **TypeAdapter(AnyRecord).json_schema()}
    out["record.schema.json"] = _dump(union)
    return out


def schema_dir(graph_root: Path) -> Path:
    return graph_root / "schema" / f"v{MAJOR_MINOR}"


def write(directory: Path) -> list[str]:
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for name, data in generate().items():
        (directory / name).write_bytes(data)
        written.append(name)
    return written


def check(directory: Path) -> list[str]:
    """Differences between the committed schema files and the models' output; empty when byte-equal."""
    problems = []
    generated = generate()
    for name, data in generated.items():
        p = directory / name
        if not p.is_file():
            problems.append(f"missing: {name}")
        elif p.read_bytes() != data:
            problems.append(f"differs from the models' output: {name}")
    for p in sorted(directory.glob("*.schema.json")):
        if p.name not in generated:
            problems.append(f"not generated by the models (stale?): {p.name}")
    return problems
